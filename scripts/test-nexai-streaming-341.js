#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const server = read('server.js');
const classic = read('public/app.js');
const enterprise = read('public/index-redesign.html');
const pkg = JSON.parse(read('package.json'));
const lock = JSON.parse(read('package-lock.json'));
assert.equal(pkg.version, '4.7.0');
assert.equal(lock.version, '4.7.0');
assert.match(server, /streamGenerateContent\?alt=sse/, 'Gemini must use its streaming endpoint');
assert.match(server, /askGeminiStream/, 'server must consume Gemini chunks');
assert.match(server, /writeChatEvent\(res, 'delta'/, 'server must forward response deltas');
assert.match(server, /writeChatEvent\(res, 'done'/, 'server must send completion metadata after persistence');
assert.match(server, /writeChatEvent\(res, 'error'/, 'server must report stream errors');
assert.match(server, /firstTokenMs/, 'first-token latency must be logged');
assert.match(server, /retryCount/, 'retry count must be logged');
assert.match(server, /if \(isNewChat\) pruneOldChats/, 'chat pruning must not run on every existing-chat turn');
assert.match(server, /CONTEXT_MESSAGES = 24/, 'Gemini history should be bounded to recent context');
assert.match(server, /Chat\.updateOne\([\s\S]*?\$push:[\s\S]*?\$slice: -MAX_CHAT_MESSAGES/, 'existing chat turns should be appended atomically');
assert.match(classic, /stream: true/, 'Classic must request streaming');
assert.match(classic, /readChatStream/, 'Classic must render streamed chunks');
assert.match(enterprise, /stream: true/, 'Enterprise must request streaming');
assert.match(enterprise, /const readStream = async response/, 'Enterprise must render streamed chunks');
assert.match(classic, /resolvedOptions\(\)\.timeZone/, 'Classic context must include the device IANA timezone');
assert.match(classic, /currentDate.*currentTime.*timeZone/s, 'schedule prompts must include current local date, time and timezone');
assert.match(classic, /forceUnscheduled: entry\.start === ''/, 'explicitly unscheduled AI items must remain unscheduled');
assert.match(server, /Never say 'you are my creator'/, 'creator identity safeguards must remain intact');
console.log('NexOS 3.4.1 NexAI streaming, timing, context and schedule checks passed.');
