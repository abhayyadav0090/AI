'use strict';
const assert = require('node:assert/strict');
const { nextReview, cleanText } = require('../lib/study-planner');
assert.deepEqual(nextReview(0, 'good', 0), { intervalDays: 1, repetitions: 1 });
assert.deepEqual(nextReview(1, 'good', 1), { intervalDays: 3, repetitions: 2 });
assert.deepEqual(nextReview(3, 'good', 2), { intervalDays: 7, repetitions: 3 });
assert.deepEqual(nextReview(7, 'again', 4), { intervalDays: 1, repetitions: 0 });
assert.deepEqual(nextReview(7, 'hard', 2), { intervalDays: 3, repetitions: 3 });
assert.equal(cleanText('  <Biology>\n  chapter  ', 20), 'Biology chapter');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const server = fs.readFileSync(path.join(root, 'server.js'), 'utf8');
const study = fs.readFileSync(path.join(root, 'lib', 'study.js'), 'utf8');
const ui = fs.readFileSync(path.join(root, 'public', 'study.js'), 'utf8');
assert.ok(server.includes('StudyReview, StudyExamPlan'), 'server registers persistent revision models');
assert.ok(server.includes('studyPlanner.createRouter'), 'revision routes are mounted');
assert.ok(server.includes('StudyReview.deleteMany') && server.includes('StudyExamPlan.deleteMany'), 'account deletion removes planner data');
assert.ok(study.includes('Review.deleteMany({ userId: req.userId, documentId: doc._id })'), 'deleting a source document removes linked review items');
assert.ok(ui.includes('data-tab="revision"') && ui.includes('Exam planner'), 'Study Studio exposes the revision and exam planner tab');
assert.ok(ui.includes("saveRevision({ topic: q.question") && ui.includes("saveRevision({ topic: c.front"), 'missed quiz questions and Again cards are tracked');
console.log('Study Studio 4.5.0 planner tests passed.');
